/**
 * Generator nomor PO & ID Internal otomatis berdasarkan sequence order sebelumnya
 */
function generateNextPoNumbers(existingOrders: FobPurchaseOrder[] = []) {
  let maxSeq = 0;

  existingOrders.forEach((o) => {
    if (o.poNumber) {
      const match = o.poNumber.match(/\d+/g);
      if (match && match.length > 0) {
        const num = parseInt(match[match.length - 1], 10);
        if (!isNaN(num) && num > maxSeq) {
          maxSeq = num;
        }
      }
    }
    if (o.internalId) {
      const match = o.internalId.match(/\d+/g);
      if (match && match.length > 0) {
        const num = parseInt(match[match.length - 1], 10);
        if (!isNaN(num) && num > maxSeq) {
          maxSeq = num;
        }
      }
    }
  });

  // Jika belum ada data sama sekali atau sequence 0, default mulai dari 0001 (atau 0003 jika ada sample 0002)
  const nextSeq = maxSeq > 0 ? maxSeq + 1 : 1;
  const padded = String(nextSeq).padStart(4, '0');

  return {
    poNumber: `PO-PH-${padded}`,
    internalId: `PH-${padded}`,
    seq: nextSeq,
  };
}

